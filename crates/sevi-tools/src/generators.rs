pub fn keep(a: &Args<'_>) -> Result {
    let source = a
        .args
        .first()
        .filter(|s| !s.starts_with('-'))
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| a.data().join("keep/keep_3.txt"));
    let mut words = BTreeSet::new();
    for w in fs::read_to_string(source)?.lines().map(str::trim) {
        if w.len() >= 3 && w.bytes().all(|c| c.is_ascii_alphabetic()) {
            words.insert(w.to_owned());
        }
    }
    let mut out = format!(
        "// Generated by Tools/autoswitch/keep/gen_inc.py — words auto-correct never changes (D26), as typed\n// keys (Telex for Vietnamese), sorted for binary search. Shorthand, slang, brands from real text.\nstatic const int kKeepWordsCount = {};\nstatic const char* const kKeepWords[] = {{\n",
        words.len()
    );
    let list: Vec<_> = words.iter().collect();
    for row in list.chunks(12) {
        out.push_str("    ");
        out.push_str(
            &row.iter()
                .map(|w| format!("\"{w}\","))
                .collect::<Vec<_>>()
                .join(" "),
        );
        out.push('\n');
    }
    out.push_str("};\n");
    let path = a.output("Engine/KeepWords.inc");
    fs::write(&path, out)?;
    println!("{} words -> {}", words.len(), path.display());
    Ok(())
}
pub fn bigrams(a: &Args<'_>) -> Result {
    let data = a.data();
    let mut ties = BTreeSet::new();
    for line in fs::read_to_string(data.join("bigram/tie_forms.tsv"))?.lines() {
        let (a, b) = line.split_once('\t').ok_or("invalid tie form")?;
        ties.insert(a.to_owned());
        ties.insert(b.nfc().collect());
    }
    let min: usize = std::env::var("SEVI_BIGRAM_MIN")
        .unwrap_or_else(|_| "10".into())
        .parse()?;
    let next_min: usize = std::env::var("SEVI_BIGRAM_NEXT_MIN")
        .unwrap_or_else(|_| "20".into())
        .parse()?;
    let mut counts = BTreeMap::<(String, String), usize>::new();
    for file in [
        "bulk/merged/bigram_vi.tsv",
        "bulk/merged/bigram_en.tsv",
        "bigram/crawl_vi.tsv",
    ] {
        for line in fs::read_to_string(data.join(file))?.lines() {
            let p: Vec<_> = line.split('\t').collect();
            if p.len() == 3 && (ties.contains(p[0]) || ties.contains(p[1])) {
                *counts.entry((p[0].into(), p[1].into())).or_default() += p[2].parse::<usize>()?;
            }
        }
    }
    let pairs: Vec<_> = counts
        .into_iter()
        .filter(|((a, b), v)| {
            (ties.contains(b) && *v >= min) || (ties.contains(a) && *v >= next_min)
        })
        .map(|((a, b), v)| (format!("{a}\t{b}"), v))
        .collect();
    let mut out="// Generated by Tools/autoswitch/build_bigrams.py. Do not edit. Word pairs for ties (D30).\n// Sources: FineWeb-2 / FineWeb (ODC-By), HPLT 2 (CC0), MADLAD-400 (ODC-By), Reddit, our forum crawl.\n#ifndef BigramData_h\n#define BigramData_h\nstatic const char kBigramKeys[] =\n".to_owned();
    let mut offsets = vec![];
    let mut pos = 0;
    for chunk in pairs.chunks(100) {
        out.push_str("    \"");
        for (k, _) in chunk {
            offsets.push(pos);
            pos += k.len() + 1;
            for b in k.bytes() {
                match b {
                    9 => out.push_str("\\t"),
                    0x80..=255 | b'"' | b'\\' => out.push_str(&format!("\\{b:03o}")),
                    _ => out.push(b as char),
                }
            }
            out.push_str("\\0");
        }
        out.push_str("\"\n");
    }
    out.push_str(";\n");
    out.push_str(&format!(
        "static const unsigned int kBigramOffsets[{}] = {{{}}};\n",
        pairs.len(),
        offsets
            .iter()
            .map(usize::to_string)
            .collect::<Vec<_>>()
            .join(",")
    ));
    out.push_str(&format!(
        "static const unsigned char kBigramLogCounts[{}] = {{{}}};\n",
        pairs.len(),
        pairs
            .iter()
            .map(|(_, v)| (8. * (*v as f64).log2())
                .round_ties_even()
                .min(255.)
                .to_string())
            .collect::<Vec<_>>()
            .join(",")
    ));
    out.push_str(&format!(
        "static const int kBigramCount = {};\n#endif\n",
        pairs.len()
    ));
    let path = a.output("Engine/BigramData.h");
    fs::write(&path, &out)?;
    println!(
        "{} pairs -> {} {} bytes",
        pairs.len(),
        path.display(),
        out.len()
    );
    Ok(())
}
fn canon(w: &str) -> String {
    let mut out = String::new();
    let mut tone = None;
    for c in w.chars() {
        if c == 'đ' {
            out.push_str("d^");
            continue;
        }
        let mut d = c.to_string().nfd().collect::<Vec<_>>().into_iter();
        if let Some(c) = d.next() {
            out.push(c)
        }
        for m in d {
            match m {
                '\u{302}' => out.push('^'),
                '\u{306}' | '\u{31b}' => out.push('+'),
                '\u{301}' => tone = Some('1'),
                '\u{300}' => tone = Some('2'),
                '\u{309}' => tone = Some('3'),
                '\u{303}' => tone = Some('4'),
                '\u{323}' => tone = Some('5'),
                _ => (),
            }
        }
    }
    if let Some(t) = tone {
        out.push(t)
    }
    out
}
fn corpus_files(path: &Path) -> Result<Vec<std::path::PathBuf>> {
    if !path.exists() {
        return Ok(vec![]);
    }
    let mut files = fs::read_dir(path)?
        .map(|e| e.map(|e| e.path()))
        .collect::<std::io::Result<Vec<_>>>()?;
    files.retain(|p| p.extension().is_some_and(|s| s == "txt") && p.is_file());
    files.sort();
    Ok(files)
}
pub fn teencode(a: &Args<'_>) -> Result {
    let mut words = BTreeSet::new();
    let vis = a.path(
        "--visolex",
        Path::new("/tmp/claude-501/visolex/dict/dictionary.json"),
    );
    if vis.exists() {
        let data: serde_json::Value = serde_json::from_slice(&fs::read(vis)?)?;
        if let Some(map) = data.as_object() {
            words.extend(
                map.keys()
                    .map(|k| k.to_lowercase().nfc().collect::<String>()),
            );
        }
    }
    let letters = regex::Regex::new(r"[\p{L}\p{Nl}\p{No}]+")?;
    let mut counts = BTreeMap::<String, usize>::new();
    let real = a.data().join("real");
    for path in corpus_files(&real)?
        .into_iter()
        .chain(corpus_files(&real.join("fresh"))?)
    {
        let text = fs::read(path)?
            .utf8_chunks()
            .map(|c| c.valid())
            .collect::<String>()
            .to_lowercase();
        for m in letters.find_iter(&text) {
            *counts.entry(m.as_str().nfc().collect()).or_default() += 1;
        }
    }
    words.extend(
        counts
            .iter()
            .filter(|(_, c)| **c >= 2)
            .map(|(w, _)| w.clone()),
    );
    let named: BTreeSet<_> = [
        "zui", "zẻ", "zô", "zậy", "dzô", "bíe", "thík", "gòy", "ừk", "mịe", "bik", "mik", "thik",
        "zìa",
    ]
    .into_iter()
    .collect();
    let pattern = regex::Regex::new(r"^(z|dz)|òy$|[iìíỉĩị]e$|[iíìịỉĩ]k$|[ưừứửữự]k$")?;
    let vi = regex::Regex::new(
        r"^[a-zàáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]+$",
    )?;
    let mark = regex::Regex::new(
        r"[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]",
    )?;
    let z = regex::Regex::new(r"^(z|dz)[aeiouy]")?;
    let ok = |w: &str| {
        let chars: Vec<_> = w.chars().collect();
        vi.is_match(w)
            && pattern.is_match(w)
            && !chars.windows(3).any(|s| s[0] == s[1] && s[1] == s[2])
            && chars.len() <= 6
            && (mark.is_match(w) || (z.is_match(w) && chars.len() <= 4))
    };
    let mut keep: BTreeSet<String> = words.iter().filter(|w| ok(w)).map(|w| canon(w)).collect();
    keep.extend(named.iter().map(|w| canon(w)));
    let total = counts.values().sum::<usize>().max(1) as f64;
    let mut scored = BTreeMap::<String, i32>::new();
    for w in words {
        if ((ok(&w) && mark.is_match(&w)) || named.contains(w.as_str()))
            && let Some(c) = counts.get(&w).filter(|c| **c >= 2)
        {
            let k = teencode_key(&w);
            let value = score(*c as f64, total);
            scored
                .entry(k)
                .and_modify(|v| *v = (*v).max(value))
                .or_insert(value);
        }
    }
    let mut out="// Generated by Tools/autoswitch/build_teencode.py (D53). Teencode words in the engine's letter form\n// (letter, ^ for â ê ô đ, + for ă ơ ư, tone digit 1-5 last). Sorted for binary search.\n#pragma once\nstatic const char* const kTeencodeWords[] = {\n".to_owned();
    for k in &keep {
        out.push_str(&format!("    \"{k}\",\n"));
    }
    out.push_str(&format!("}};\nstatic const int kTeencodeCount = {};\n// Vietnamese scores of teencode words that occur in our data, by engine key (zô -> \"zoo\"), for the tie rules.\nstatic const char* const kTeencodeVnKeys[] = {{{}}};\nstatic const signed char kTeencodeVnScores[] = {{{}}};\nstatic const int kTeencodeVnCount = {};\n",keep.len(),scored.keys().map(|k|format!("\"{k}\"")).collect::<Vec<_>>().join(", "),scored.values().map(i32::to_string).collect::<Vec<_>>().join(", "),scored.len()));
    fs::write(a.output("Engine/TeencodeData.h"), out)?;
    println!("{} teencode words, {} scores", keep.len(), scored.len());
    Ok(())
}
fn teencode_key(w: &str) -> String {
    let mut out = String::new();
    let mut tone = None;
    for c in w.chars() {
        if c == 'đ' {
            out.push_str("dd");
            continue;
        }
        let units: Vec<_> = c.to_string().nfd().collect();
        out.push(units[0]);
        for m in &units[1..] {
            match m {
                '\u{302}' => out.push(units[0]),
                '\u{306}' | '\u{31b}' => out.push('w'),
                '\u{301}' => tone = Some('s'),
                '\u{300}' => tone = Some('f'),
                '\u{309}' => tone = Some('r'),
                '\u{303}' => tone = Some('x'),
                '\u{323}' => tone = Some('j'),
                _ => (),
            }
        }
    }
    if let Some(t) = tone {
        out.push(t)
    }
    out
}
